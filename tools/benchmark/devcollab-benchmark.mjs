#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { performance } from 'node:perf_hooks';

const DEFAULT_BASE_URL = 'http://localhost:8080';
const DEFAULT_PASSWORD = 'Benchmark@123456';

const args = parseArgs(process.argv.slice(2));
const command = args._[0] ?? 'help';

async function seed() {
  const baseUrl = option('base-url', DEFAULT_BASE_URL);
  const username = option('username', `bench_${Date.now()}`);
  const password = option('password', DEFAULT_PASSWORD);
  const workspaces = numberOption('workspaces', 1);
  const documents = numberOption('documents', 200);
  const childPerRoot = numberOption('child-per-root', 4);
  const blocksPerDocument = numberOption('blocks-per-document', 2);
  const output = option('output', 'tools/benchmark/.benchmark-seed.json');

  const client = new ApiClient(baseUrl);
  const auth = await client.post('/api/v1/auth/register', {
    username,
    displayName: `Benchmark User ${new Date().toISOString()}`,
    password,
  });
  client.accessToken = auth.accessToken;

  const seedData = {
    baseUrl,
    username,
    password,
    generatedAt: new Date().toISOString(),
    workspaces: [],
  };

  for (let workspaceIndex = 0; workspaceIndex < workspaces; workspaceIndex += 1) {
    const workspace = await client.post('/api/v1/workspaces', {
      name: `Benchmark Workspace ${workspaceIndex + 1} ${Date.now()}`,
    });

    const workspaceData = {
      id: workspace.id,
      documents: [],
    };

    const rootIds = [];
    for (let index = 0; index < documents; index += 1) {
      const shouldBeChild = rootIds.length > 0 && index % (childPerRoot + 1) !== 0;
      const parentDocumentId = shouldBeChild
        ? rootIds[rootIds.length - 1]
        : null;
      const document = await client.post(`/api/v1/workspaces/${workspace.id}/documents`, {
        title: `Benchmark Doc ${workspaceIndex + 1}-${index + 1}`,
        parentDocumentId,
        documentType: index % 5 === 0 ? 'API' : 'REQUIREMENT',
      });

      if (!parentDocumentId) {
        rootIds.push(document.id);
      }

      for (let blockIndex = 0; blockIndex < blocksPerDocument; blockIndex += 1) {
        await client.post(`/api/v1/documents/${document.id}/blocks`, {
          type: 'PARAGRAPH',
          content: {
            text: [
              `Benchmark content for ${document.title}`,
              `block=${blockIndex + 1}`,
              `workspace=${workspace.id}`,
              'redis cache benchmark permission document tree',
            ].join(' '),
          },
        });
      }

      workspaceData.documents.push({
        id: document.id,
        title: document.title,
        parentDocumentId: document.parentDocumentId,
      });

      if ((index + 1) % 50 === 0 || index + 1 === documents) {
        console.log(`[seed] workspace=${workspace.id} documents=${index + 1}/${documents}`);
      }
    }

    seedData.workspaces.push(workspaceData);
  }

  await writeJson(output, seedData);
  console.log(`[seed] wrote ${output}`);
}

async function runBenchmark() {
  const seedFile = option('seed', 'tools/benchmark/.benchmark-seed.json');
  const seedData = JSON.parse(await readFile(seedFile, 'utf8'));
  const baseUrl = option('base-url', seedData.baseUrl ?? DEFAULT_BASE_URL);
  const username = option('username', seedData.username);
  const password = option('password', seedData.password ?? DEFAULT_PASSWORD);
  const label = option('label', 'benchmark');
  const warmup = numberOption('warmup', 20);
  const iterations = numberOption('iterations', 200);
  const concurrency = numberOption('concurrency', 8);
  const output = option(
    'output',
    `tools/benchmark/results/${new Date().toISOString().replaceAll(':', '-')}-${label}.json`,
  );

  if (!username) {
    throw new Error('Missing username. Pass --username or use a seed file generated by seed command.');
  }

  const workspace = seedData.workspaces?.[0];
  const document = workspace?.documents?.[Math.floor((workspace.documents.length - 1) / 2)];
  if (!workspace || !document) {
    throw new Error(`Invalid seed file: ${seedFile}`);
  }

  const client = new ApiClient(baseUrl);
  const auth = await client.post('/api/v1/auth/login', { username, password });
  client.accessToken = auth.accessToken;

  const scenarios = [
    {
      name: 'document-tree',
      method: 'GET',
      path: `/api/v1/workspaces/${workspace.id}/documents/tree`,
    },
    {
      name: 'document-summary',
      method: 'GET',
      path: `/api/v1/documents/${document.id}`,
    },
    {
      name: 'document-blocks',
      method: 'GET',
      path: `/api/v1/documents/${document.id}/blocks`,
    },
  ];

  const scenarioResults = [];
  for (const scenario of scenarios) {
    console.log(`[run] ${scenario.name} warmup=${warmup} iterations=${iterations} concurrency=${concurrency}`);
    await executeScenario(client, scenario, warmup, concurrency);
    const durations = await executeScenario(client, scenario, iterations, concurrency);
    const stats = summarize(durations);
    scenarioResults.push({
      ...scenario,
      ...stats,
    });
    console.log(
      `[run] ${scenario.name} avg=${stats.avgMs}ms p95=${stats.p95Ms}ms p99=${stats.p99Ms}ms qps=${stats.qps}`,
    );
  }

  const result = {
    label,
    baseUrl,
    seedFile,
    measuredAt: new Date().toISOString(),
    warmup,
    iterations,
    concurrency,
    workspaceId: workspace.id,
    documentId: document.id,
    scenarios: scenarioResults,
  };

  await writeJson(output, result);
  console.log(`[run] wrote ${output}`);
}

async function compareResults() {
  const files = args._.slice(1);
  if (files.length < 2) {
    throw new Error('compare requires at least two result files.');
  }

  const results = [];
  for (const file of files) {
    results.push(JSON.parse(await readFile(file, 'utf8')));
  }

  const scenarioNames = new Set(results.flatMap((result) => result.scenarios.map((scenario) => scenario.name)));
  const lines = [];
  lines.push('| Scenario | Metric | ' + results.map((result) => result.label).join(' | ') + ' |');
  lines.push('|---|---|' + results.map(() => '---|').join(''));

  for (const scenarioName of scenarioNames) {
    for (const metric of ['avgMs', 'p50Ms', 'p95Ms', 'p99Ms', 'qps']) {
      const values = results.map((result) => {
        const scenario = result.scenarios.find((item) => item.name === scenarioName);
        return scenario ? String(scenario[metric]) : '-';
      });
      lines.push(`| ${scenarioName} | ${metric} | ${values.join(' | ')} |`);
    }
  }

  const output = option('output', '');
  const markdown = lines.join('\n');
  if (output) {
    await writeFile(output, `${markdown}\n`, 'utf8');
    console.log(`[compare] wrote ${output}`);
  } else {
    console.log(markdown);
  }
}

async function executeScenario(client, scenario, total, concurrency) {
  const durations = [];
  let nextIndex = 0;

  async function worker() {
    while (nextIndex < total) {
      nextIndex += 1;
      const started = performance.now();
      await client.request(scenario.method, scenario.path);
      durations.push(performance.now() - started);
    }
  }

  await Promise.all(Array.from({ length: concurrency }, () => worker()));
  return durations;
}

function summarize(durations) {
  const sorted = [...durations].sort((a, b) => a - b);
  const totalMs = sorted.reduce((sum, value) => sum + value, 0);
  return {
    count: sorted.length,
    minMs: round(sorted[0] ?? 0),
    avgMs: round(totalMs / Math.max(1, sorted.length)),
    p50Ms: round(percentile(sorted, 0.50)),
    p95Ms: round(percentile(sorted, 0.95)),
    p99Ms: round(percentile(sorted, 0.99)),
    maxMs: round(sorted[sorted.length - 1] ?? 0),
    qps: round((sorted.length / Math.max(totalMs, 1)) * 1000),
  };
}

function percentile(sorted, ratio) {
  if (sorted.length === 0) {
    return 0;
  }
  const index = Math.min(sorted.length - 1, Math.ceil(sorted.length * ratio) - 1);
  return sorted[index];
}

function round(value) {
  return Math.round(value * 100) / 100;
}

async function writeJson(file, value) {
  const absolutePath = resolve(file);
  await mkdir(dirname(absolutePath), { recursive: true });
  await writeFile(absolutePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function parseArgs(values) {
  const parsed = { _: [] };
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (!value.startsWith('--')) {
      parsed._.push(value);
      continue;
    }

    const key = value.slice(2);
    const next = values[index + 1];
    if (!next || next.startsWith('--')) {
      parsed[key] = true;
    } else {
      parsed[key] = next;
      index += 1;
    }
  }
  return parsed;
}

function option(name, fallback) {
  return args[name] === undefined ? fallback : args[name];
}

function numberOption(name, fallback) {
  const value = Number(option(name, fallback));
  if (!Number.isFinite(value) || value <= 0) {
    throw new Error(`Invalid --${name}: ${option(name, fallback)}`);
  }
  return value;
}

class ApiClient {
  constructor(baseUrl) {
    this.baseUrl = baseUrl.replace(/\/$/, '');
    this.accessToken = null;
  }

  async get(path) {
    return this.request('GET', path);
  }

  async post(path, body) {
    return this.request('POST', path, body);
  }

  async request(method, path, body) {
    let response;
    try {
      response = await fetch(`${this.baseUrl}${path}`, {
        method,
        headers: {
          Accept: 'application/json',
          ...(body === undefined ? {} : { 'Content-Type': 'application/json' }),
          ...(this.accessToken ? { Authorization: `Bearer ${this.accessToken}` } : {}),
        },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
    } catch (error) {
      const cause = error instanceof Error && error.cause instanceof Error
        ? `: ${error.cause.message}`
        : '';
      throw new Error(
        `${method} ${this.baseUrl}${path} failed to connect${cause}. `
        + 'Check that Knowledge Core is running and --base-url points to the correct port.',
      );
    }

    const text = await response.text();
    if (!response.ok) {
      throw new Error(`${method} ${path} failed: ${response.status} ${text}`);
    }
    return text ? JSON.parse(text) : null;
  }
}

function printHelp() {
  console.log(`
DevCollab benchmark helper

Commands:
  seed      create benchmark user, workspace, documents and blocks
  run       measure selected read endpoints using a seed file
  compare   print markdown comparison table from result files

Examples:
  node tools/benchmark/devcollab-benchmark.mjs seed --documents 500 --blocks-per-document 2
  node tools/benchmark/devcollab-benchmark.mjs run --label no-cache --iterations 300 --concurrency 16
  node tools/benchmark/devcollab-benchmark.mjs run --label redis --iterations 300 --concurrency 16
  node tools/benchmark/devcollab-benchmark.mjs compare tools/benchmark/results/no-cache.json tools/benchmark/results/redis.json
`);
}

async function main() {
  if (command === 'help' || args.help) {
    printHelp();
    return;
  }

  if (command === 'seed') {
    await seed();
    return;
  }

  if (command === 'run') {
    await runBenchmark();
    return;
  }

  if (command === 'compare') {
    await compareResults();
    return;
  }

  throw new Error(`Unknown command: ${command}`);
}

try {
  await main();
} catch (error) {
  console.error(`[benchmark] ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
